export type WageChange = {
  type: "increase" | "decrease";
  oldWage: string;
  newWage: string;
  delta: string;
  effectiveOn: string;
  changedBy: string;
  changedOn: string;
};

export type MoneyCell = {
  value: string;
  detail?: string;
  wageChange?: WageChange;
};

